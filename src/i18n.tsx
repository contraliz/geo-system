const compactTranslations = new Map(Object.entries(translations).map(([key, value]) => [key.replace(/\s+/g, ' ').trim(), value]))

export function translateText(value: string, language: Language): string {
  if (language === 'en') return value
  const normalized = value.replace(/\s+/g, ' ').trim()
  if (compactTranslations.has(normalized)) return compactTranslations.get(normalized)!

  const dynamicRules: Array<[RegExp, (match: RegExpExecArray) => string]> = [
    [/^(.+) created locally$/, match => `${match[1]} 已在本地创建`],
    [/^(.+) deleted locally$/, match => `${match[1]} 已在本地删除`],
    [/^(.+) duplicated locally$/, match => `${match[1]} 已在本地复制`],
    [/^(.+) completed locally$/, match => `${match[1]} 已在本地完成`],
    [/^(.+) saved locally$/, match => `${match[1]} 已在本地保存`],
    [/^(.+) queued locally$/, match => `${match[1]} 已在本地排队`],
    [/^(.+) is now (.+) locally$/, match => `${match[1]} 现在为${translateText(match[2], 'zh')}`],
    [/^(.+) is now (.+)$/, match => `${match[1]} 现在为${translateText(match[2], 'zh')}`],
    [/^(.+) moved to (.+) locally$/, match => `${match[1]} 已在本地移至${translateText(match[2], 'zh')}`],
    [/^Article status changed to (.+)$/, match => `文章状态已更改为${translateText(match[1], 'zh')}`],
    [/^Knowledge entry marked (.+)$/, match => `知识条目已标记为${translateText(match[1], 'zh')}`],
    [/^Knowledge source marked (.+)$/, match => `知识来源已标记为${translateText(match[1], 'zh')}`],
    [/^Knowledge fact marked (.+)$/, match => `知识事实已标记为${translateText(match[1], 'zh')}`],
    [/^(.+) marked (.+) locally$/, match => `${match[1]} 已在本地标记为${translateText(match[2], 'zh')}`],
    [/^(.+) status changed to (.+)$/, match => `${match[1]} 状态已更改为${translateText(match[2], 'zh')}`],
    [/^Delete (.+)\?$/, match => `确定删除 ${match[1]} 吗？`],
    [/^Delete “(.+)”\?$/, match => `确定删除“${match[1]}”吗？`],
    [/^Duplicate (.+)$/, match => `复制 ${match[1]}`],
    [/^More actions for (.+)$/, match => `${match[1]} 的更多操作`],
    [/^\+(\d[\d,.]*) points simulated$/, match => `已模拟增加 ${match[1]} 点`],
    [/^(\d[\d,]*) points simulated$/, match => `已模拟增加 ${match[1]} 点`],
    [/^(\d+) validation results$/, match => `${match[1]} 条验证结果`],
    [/^(\d+) prompts · (.+)$/, match => `${match[1]} 个提示词 · ${match[2]}`],
    [/^(\d+) articles generated · (.+)$/, match => `已生成 ${match[1]} 篇文章 · ${match[2]}`],
    [/^Created (\d+) review article records? locally; no model call or network request was made\.$/, match => `已在本地创建 ${match[1]} 条审核文章记录；未调用模型或发起网络请求。`],
    [/^Mode (.+) · daily limit (\d+)$/, match => `模式 ${translateText(match[1], 'zh')} · 每日限制 ${match[2]}`],
    [/^(.+) · last seen (.+)$/, match => `${match[1]} · 最近查看 ${match[2]}`],
    [/^(.+) · created (.+)$/, match => `${match[1]} · 创建于 ${match[2]}`],
    [/^(.+) · released (.+)$/, match => `${match[1]} · 发布于 ${match[2]}`],
    [/^Owner: (.+)$/, match => `负责人：${match[1]}`],
    [/^(\d+) \/ run$/, match => `${match[1]} / 次`],
    [/^(.+) · (.+) approval · (.+)$/, match => `${match[1]} · ${match[2]} 审核 · ${match[3]}`],
    [/^Hello, (.+) — profile saved locally$/, match => `你好，${match[1]} — 资料已在本地保存`],
    [/^(\d+) articles · model attribution is simulated$/, match => `${match[1]} 篇文章 · 模型归属为模拟数据`],
    [/^(\d+) validation results · simulated model output$/, match => `${match[1]} 条验证结果 · 模型输出为模拟数据`],
    [/^(\d+) local records$/, match => `${match[1]} 条本地记录`],
    [/^Page (\d+)$/, match => `第 ${match[1]} 页`],
    [/^This article is a local simulated output attributed to (.+)\. Review claims against the selected knowledge base before publishing\.$/, match => `这篇文章是归属于 ${match[1]} 的本地模拟输出。发布前请对照所选知识库审核事实声明。`],
    [/^Live agent produced a reviewable draft via (.+)$/, match => `实时代理已通过 ${match[1]} 生成可审核草稿`],
    [/^Live agent failed — (.+)$/, match => `实时代理失败 — ${match[1]}`],
    [/^Inspect (.+)$/, match => `查看 ${match[1]}`],
    [/^Edit (.+)$/, match => `编辑 ${match[1]}`],
    [/^(\d+) creation tasks? references? this instruction$/, match => `${match[1]} 个创作任务引用此指令`],
    [/^(\d+) image stored locally from your device$/, match => `已在此浏览器保存 ${match[1]} 张图片`],
    [/^(\d+) images stored locally from your device$/, match => `已在此浏览器保存 ${match[1]} 张图片`],
    [/^Skipped: (.+)$/, match => `已跳过：${match[1]}`],
  ]
  for (const [pattern, handler] of dynamicRules) {
    const match = pattern.exec(normalized)
    if (match) return handler(match)
  }
  return value
}

type I18nContextValue = { language: Language; setLanguage: (language: Language) => void; t: (value: string) => string }

const I18nContext = createContext<I18nContextValue>({ language: 'en', setLanguage: () => undefined, t: value => value })

export function I18nProvider({ language, onLanguageChange, children }: { language?: Language; onLanguageChange?: (language: Language) => void; children: ReactNode }) {
  const currentLanguage: Language = language === 'zh' ? 'zh' : 'en'
  const value = useMemo<I18nContextValue>(() => ({
    language: currentLanguage,
    setLanguage: (next: Language) => onLanguageChange?.(next),
    t: (value: string) => translateText(value, currentLanguage),
  }), [currentLanguage, onLanguageChange])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useTranslation() {
  return useContext(I18nContext)
}
